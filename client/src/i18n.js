export function translateError(msg, t) {
  if (!msg) return '';
  const n = (msg.match(/\d+/) || [])[0] || null;
  if (/minimum bet/i.test(msg)) return t('errMinBet').replace('{n}', n || '');
  if (/betting is closed/i.test(msg)) return t('errBetClosed');
  if (/already placed/i.test(msg)) return t('errDoubleBet');
  if (/insufficient/i.test(msg)) return t('errNoBalance');
  if (/bet failed/i.test(msg)) return t('errBetFailed');
  if (/cashout failed/i.test(msg)) return t('errCashoutFailed');
  if (/not running/i.test(msg)) return t('errNotRunning');
  if (/invalid bet type/i.test(msg)) return t('errBadType');
  if (/join match/i.test(msg)) return t('errJoinMatch');
  if (/create match|create game/i.test(msg)) return t('errCreateMatch');
  return msg;
}

